export interface XmlEmitterOptions {
  /** Module the generated runtime imports LmlError from. */
  readonly contractsModule?: string;
}

const DEFAULT_CONTRACTS_MODULE = "lutaml-model-ts";
const HEADER = "// Generated by lutaml-model-ts. Do not edit.\n";
const POLICIES = new Set(["omit", "as_nil", "as_empty", "as_blank"]);
const STRING_FAMILY = new Set(["string", "token", "uri", "email", "hostname", "ip", "symbol", "date", "date_time", "time", "time_without_date", "duration",
  "email_address", "ip_v4_address", "ip_v6_address", "uuid", "reference", "uri_reference", "date_with_timezone", "date_time_with_timezone", "day_time_duration", "year_month_duration"]);
const EXACT_BUILTINS = new Set(["decimal", "rational"]);
const MAPPING_KEYS = new Set(["root", "namespace", "rules", "ordered", "mixed_content", "sequence"]);
const RULE_KEYS = new Set(["kind", "name", "to", "namespace", "prefix", "cdata", "render", "discriminator"]);

function byCodePoint(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

const q = (value: unknown): string => JSON.stringify(value);

class Refusal {
  constructor(private readonly modelId: ModelId) {}

  unsupported(detail: string, attribute?: string, rule?: string): never {
    return this.raise("unsupported_mapping", detail, attribute, rule);
  }

  raise(reason: ErrorDetail["reason"], detail: string, attribute?: string, rule?: string): never {
    throw new LmlError({
      reason,
      model_id: this.modelId,
      format: "xml",
      detail,
      ...(attribute === undefined ? {} : { attribute }),
      ...(rule === undefined ? {} : { rule }),
    });
  }
}

/** A scalar wire form: reader expression over (text, el), writer expression over a value. */
interface Scalar {
  readonly dec: string;
  readonly enc: string;
  /** An empty text reads as a value (string family) rather than nil. */
  readonly textual: boolean;
}

interface NsInfo {
  readonly uri: string | null;
  readonly prefix: string | null;
}

class Context {
  private readonly bound = new Map<string, { readonly alias: string; readonly binding: TypeBinding }>();
  readonly tables: string[] = [];

  constructor(
    readonly bundle: Bundle,
    readonly bindings: Bindings,
    readonly classNames: ReadonlyMap<ModelId, string>,
  ) {}

  mapping(id: ModelId): XmlMapping | undefined {
    return this.bundle.models[id]?.mappings.xml;
  }

  bind(binding: TypeBinding): string {
    const id = binding.module + "\u0000" + binding.export + (binding.xmlLexical ? "\u0000xml" : "");
    const known = this.bound.get(id);
    if (known !== undefined) return known.alias;
    const alias = `_b${this.bound.size}`;
    this.bound.set(id, { alias, binding });
    return alias;
  }

  importLines(): string[] {
    return [...this.bound.values()].map(({ alias, binding }) => {
      const e = binding.export + (binding.xmlLexical ? "Xml" : "");
      return `import { format${e} as ${alias}_format, parse${e} as ${alias}_parse } from ${q(fromSubdirectory(binding.module))};`;
    });
  }

  /** The namespace a model's mapping declares (inherit/unqualified: none). */
  modelNs(id: ModelId): NsInfo {
    return namespaceInfo(this.mapping(id)?.namespace);
  }
}

function namespaceInfo(spec: NamespaceSpec | undefined): NsInfo {
  if (spec === undefined || spec.mode !== "uri") return { uri: null, prefix: null };
  return { uri: spec.uri, prefix: spec.prefix ?? null };
}

function scalarFor(ctx: Context, name: string, refuse: Refusal, attribute: string): Scalar {
  if (name === "double") refuse.raise("unsupported_type", name, attribute);
  if (STRING_FAMILY.has(name)) return { dec: "x.dStr", enc: "x.eStr", textual: true };
  if (EXACT_BUILTINS.has(name)) {
    const binding = ctx.bindings.types[`builtin:${name}`];
    if (binding === undefined) {
      return refuse.raise("missing_type_binding", `exact ${name} needs a binding under builtin:${name}`, attribute);
    }
    return boundScalar(ctx, binding);
  }
  switch (name) {
    case "boolean": return { dec: "x.orNil(x.dBool)", enc: "x.eBool", textual: false };
    case "positive_integer":
    case "non_negative_integer":
    case "integer": return { dec: "x.orNil(x.dInt)", enc: "x.eInt", textual: false };
    case "float": return { dec: "x.orNil(x.dFloat)", enc: "x.eFloat", textual: false };
    case "qname": return { dec: "x.orNil(x.dQName)", enc: "x.eQName", textual: false };
    case "base64_binary": return { dec: "x.orNil(x.dBase64)", enc: "x.eBase64", textual: false };
    case "hex_binary": return { dec: "x.orNil(x.dHex)", enc: "x.eHex", textual: false };
    case "hash": return refuse.unsupported("hash values have no XML text form", attribute);
    default: return refuse.raise("unknown_type", name, attribute);
  }
}

function boundScalar(ctx: Context, binding: TypeBinding): Scalar {
  const alias = ctx.bind(binding);
  return {
    dec: binding.xmlLexical
      ? `(s) => x.dBound(s, ${alias}_parse)`
      : `x.orNil((s) => x.dBound(s, ${alias}_parse))`,
    enc: `(v) => x.eBound(v, ${alias}_format)`,
    textual: false,
  };
}

function scalarOf(ctx: Context, attr: AttributeSpec, refuse: Refusal): Scalar {
  const { type } = attr;
  if (type.kind === "builtin") return scalarFor(ctx, type.name, refuse, attr.name);
  if (type.kind === "value") {
    const spec = ctx.bundle.value_types[type.id];
    if (spec === undefined) return refuse.raise("dangling_reference", `value type ${type.id}`, attr.name);
    const binding = Object.hasOwn(ctx.bindings.types, type.id) ? ctx.bindings.types[type.id] : undefined;
    if (binding !== undefined) {
      if (spec.base === "double") refuse.raise("unsupported_type", spec.base, attr.name);
      return boundScalar(ctx, binding);
    }
    return scalarFor(ctx, spec.base, refuse, attr.name);
  }
  return refuse.unsupported("a model-typed attribute cannot be an XML attribute or text", attr.name);
}

function acceptList(uris: readonly (string | null)[]): string {
  return `[${[...new Set(uris.map((u) => u ?? ""))].map(q).join(", ")}]`;
}

function nsOut(uri: string | null, prefix: string | null): string {
  return uri === null ? "null" : `{ uri: ${q(uri)}, prefix: ${prefix === null ? "null" : q(prefix)} }`;
}

function policyOf(rule: XmlRule, refuse: Refusal): { nil: string; empty: string } {
  const render = rule.render ?? {};
  for (const name of Object.keys(render)) {
    if (name !== "nil" && name !== "empty" && name !== "default") {
      refuse.unsupported(`render ${name} is not an XML render policy`, rule.to, rule.name?.[0]);
    }
  }
  if (render["default"] !== undefined && typeof render["default"] !== "boolean") {
    refuse.unsupported("render default must be boolean", rule.to);
  }
  const pick = (key: "nil" | "empty"): string => {
    const value = render[key] ?? "omit";
    if (typeof value !== "string" || !POLICIES.has(value)) {
      return refuse.unsupported(`render ${key} policy ${q(value)}`, rule.to);
    }
    return value;
  };
  return { nil: pick("nil"), empty: pick("empty") };
}

function checkNamespace(spec: NamespaceSpec | undefined, refuse: Refusal, rule?: string): void {
  if (spec === undefined) return;
  const mode = (spec as { readonly mode?: unknown }).mode;
  if (mode === "inherit" || mode === "unqualified") return;
  if (mode === "uri" && typeof (spec as { readonly uri?: unknown }).uri === "string" && (spec as { readonly uri: string }).uri !== "") return;
  refuse.raise("invalid_document", `namespace ${q(spec)} is not one of inherit, unqualified, uri`, undefined, rule);
}

interface ModelPlan {
  readonly reader: string;
  readonly writer: string;
  readonly codec: string;
}

function sameDeclaration(left: unknown, right: unknown): boolean {
  if (left === right) return true;
  if (typeof left !== "object" || left === null || typeof right !== "object" || right === null) return false;
  if (Array.isArray(left) !== Array.isArray(right)) return false;
  const a = left as Record<string, unknown>;
  const b = right as Record<string, unknown>;
  const keys = Object.keys(a);
  return keys.length === Object.keys(b).length &&
    keys.every((key) => Object.hasOwn(b, key) && sameDeclaration(a[key], b[key]));
}

function flatSequence(mapping: XmlMapping, groups: unknown): boolean {
  if (!Array.isArray(groups) || groups.length !== 1) return false;
  const group = groups[0] as { readonly kind?: unknown; readonly members?: unknown } | null;
  if (group === null || typeof group !== "object" || group.kind !== "sequence" ||
      Object.keys(group).some((key) => key !== "kind" && key !== "members")) return false;
  const elements = mapping.rules.filter((rule) => rule.kind === "element");
  return elements.length > 0 && sameDeclaration(elements, group.members);
}

function emitModel(ctx: Context, id: ModelId, doc: ModelDocument, cls: string, mapping: XmlMapping): ModelPlan {
  const refuse = new Refusal(id);
  const extra = mapping as XmlMapping & { readonly [name: string]: unknown };
  for (const key of Object.keys(extra)) {
    if (!MAPPING_KEYS.has(key)) refuse.unsupported(`mapping-level ${key} is not supported`);
  }
  checkNamespace(mapping.namespace, refuse);
  const ordered = extra["ordered"] === true;
  const mixed = extra["mixed_content"] === true || (mapping.root as { readonly mixed?: boolean } | null)?.mixed === true;
  const tokens = doc.ordered_content !== undefined;
  if ((ordered || mixed) && !tokens) {
    refuse.raise("invalid_ordered_content", "ordered/mixed mapping without an ordered_content member");
  }
  const writerRefusals: string[] = [];
  const simpleSequence = !tokens && !ordered && !mixed && flatSequence(mapping, extra["sequence"]);
  if (extra["sequence"] !== undefined && !simpleSequence) {
    writerRefusals.push("the sequence compositor is not written by this emitter");
  }

  const own = ctx.modelNs(id);
  const attrs = new Map(doc.attributes.map((a) => [a.name, a] as const));
  const seen = new Set<string>();
  const readAttrs: string[] = [];
  const claimedAttrs: string[] = [];
  const readElems: string[] = [];
  const writeAttrs: string[] = [];
  const writeElems: string[] = [];
  let readContent = "null";
  let writeContent = "null";
  let contentSeen = false;
  let anyAttribute: string | null = null;

  for (const rule of mapping.rules) {
    if (rule.kind === "any_attribute") {
      // map_all_attributes: `{kind, to}` only, one per mapping, a non-collection hash attribute.
      for (const key of Object.keys(rule)) {
        if (key !== "kind" && key !== "to") refuse.unsupported(`any_attribute carries only kind and to, not ${key}`, rule.to);
      }
      if (anyAttribute !== null) refuse.unsupported("at most one any_attribute rule per mapping", rule.to);
      const target = attrs.get(rule.to);
      if (target === undefined) refuse.raise("dangling_reference", `any_attribute maps unknown attribute ${rule.to}`, rule.to);
      const targetType = (target as AttributeSpec).type;
      if (targetType.kind !== "builtin" || targetType.name !== "hash" || ((target as AttributeSpec).collection ?? false) !== false) {
        refuse.unsupported("any_attribute needs a non-collection hash attribute", rule.to);
      }
      anyAttribute = rule.to;
      continue;
    }
    for (const key of Object.keys(rule)) {
      if (!RULE_KEYS.has(key)) refuse.unsupported(`rule-level ${key} is not supported`, rule.to);
    }
    const attr = attrs.get(rule.to);
    if (attr === undefined) refuse.raise("dangling_reference", `rule maps unknown attribute ${rule.to}`, rule.to);
    const spec = attr as AttributeSpec;
    const key = `${rule.kind}:${rule.to}`;
    if (seen.has(key)) refuse.unsupported("several rules on one attribute", rule.to);
    seen.add(key);
    checkNamespace(rule.namespace, refuse, rule.name?.[0]);
    const policy = policyOf(rule, refuse);
    const collection = ((spec as Partial<AttributeSpec>).collection ?? false) !== false;

    if (rule.kind === "content") {
      if (contentSeen) refuse.unsupported("several content rules", rule.to);
      contentSeen = true;
      scalarOf(ctx, spec, refuse);
      readContent = `{ to: ${q(rule.to)}, collection: ${collection} }`;
      writeContent = `{ to: ${q(rule.to)}, collection: ${collection}, cdata: ${rule.cdata === true} }`;
      if (rule.cdata === true) writerRefusals.push(`content rule ${rule.to} is cdata`);
      continue;
    }
    if (!Array.isArray(rule.name) || rule.name.length === 0 || rule.name.some((n) => typeof n !== "string" || n === "")) {
      refuse.raise("invalid_document", "rule needs XML names", rule.to);
    }
    const names = rule.name as readonly string[];
    const first = names[0] as string;
    const mode = rule.namespace?.mode ?? "inherit";

    if (rule.kind === "attribute") {
      if (collection) refuse.unsupported("a collection cannot be one XML attribute", rule.to, first);
      const scalar = scalarOf(ctx, spec, refuse);
      const uri = rule.namespace?.mode === "uri" ? rule.namespace.uri : null;
      const prefix = rule.prefix ?? (rule.namespace?.mode === "uri" ? rule.namespace.prefix ?? null : null);
      if (uri !== null && prefix === null) {
        writerRefusals.push(`attribute ${first} is in namespace ${uri} but declares no prefix`);
      }
      claimedAttrs.push(...names);
      readAttrs.push(`    { to: ${q(rule.to)}, names: ${q(names)}, ns: ${acceptList([uri])}, dec: ${scalar.dec} },`);
      writeAttrs.push(
        `    { to: ${q(rule.to)}, name: ${q(first)}, ns: ${nsOut(uri, prefix)}, enc: ${scalar.enc}, nil: ${q(policy.nil)}, empty: ${q(policy.empty)} },`,
      );
      continue;
    }

    // element rule
    const disc = effectiveDiscriminator(doc, spec, id);
    let dec: string;
    let child: string | null = null;
    let enc: string | null = null;
    let target: NsInfo = own;
    if (spec.type.kind === "model") {
      const modelId = spec.type.id;
      target = ctx.modelNs(modelId);
      if (ctx.mapping(modelId) === undefined) {
        refuse.unsupported(`referenced model ${modelId} has no xml mapping`, rule.to, first);
      }
      const baseClass = ctx.classNames.get(modelId);
      if (baseClass === undefined) refuse.raise("dangling_reference", `model ${modelId}`, rule.to, first);
      if (disc === undefined) {
        dec = `read${baseClass}`;
        child = `write${baseClass}`;
      } else {
        const baseRule = ctx.mapping(modelId)?.rules.find((r) => r.kind === "attribute" && r.to === disc.attribute);
        if (baseRule === undefined || baseRule.name === undefined) {
          refuse.unsupported(`discriminator attribute ${disc.attribute} has no xml attribute rule on ${modelId}`, rule.to, first);
        }
        const dnames = (baseRule as XmlRule).name as readonly string[];
        const dns = (baseRule as XmlRule).namespace;
        const dAccept = acceptList([dns?.mode === "uri" ? dns.uri : null]);
        const targets = [...new Set(Object.values(disc.cases))].sort(byCodePoint);
        if (targets.length === 0) refuse.raise("unknown_discriminator", "no cases", rule.to, first);
        const classOf = (t: ModelId): string => {
          const name = ctx.classNames.get(t);
          if (name === undefined || ctx.mapping(t) === undefined) {
            return refuse.unsupported(`discriminator case ${t} has no xml mapping`, rule.to, first);
          }
          return name;
        };
        const ladder = targets.includes(modelId) ? targets : [...targets, modelId];
        const union = ladder.map((t) => `m.${classOf(t)}`).join(" | ");
        const table = `POLY${ctx.tables.length}`;
        const entries = Object.keys(disc.cases).sort(byCodePoint).map((c) => `[${q(c)}, read${classOf(disc.cases[c] as ModelId)}]`);
        ctx.tables.push(
          `const ${table}: ReadonlyMap<string, (el: x.El) => ${union}> = new Map<string, (el: x.El) => ${union}>([${entries.join(", ")}]);`,
        );
        dec = `(el: x.El) => x.poly(el, ${q(dnames)}, ${dAccept}, ${table}, read${classOf(modelId)})`;
        const tests = ladder.map((t) => `v instanceof m.${classOf(t)} ? write${classOf(t)}(w, host, v, name, ns) : `).join("");
        child = `(w, host, v: ${union}, name, ns) => ${tests}x.xmlFail("value is not an instance of a declared discriminator case", "", "unknown_discriminator")`;
      }
    } else {
      const scalar = scalarOf(ctx, spec, refuse);
      dec = `x.leaf(${scalar.dec})`;
      enc = scalar.enc;
    }

    let accept: string;
    let out: string;
    if (mode === "uri" && rule.namespace?.mode === "uri") {
      accept = acceptList([rule.namespace.uri]);
      out = nsOut(rule.namespace.uri, rule.prefix ?? rule.namespace.prefix ?? null);
    } else if (mode === "unqualified") {
      accept = acceptList([null]);
      out = "null";
    } else {
      accept = acceptList(target.uri === null ? [null] : [target.uri, null]);
      out = nsOut(target.uri, target.prefix);
    }
    if (rule.cdata === true) writerRefusals.push(`rule ${first} is cdata`);
    // A native sequence of repeated elements maps an omitted rule to an empty
    // collection. An empty collection emits no occurrences even with render_empty.
    const repeatedSequence = simpleSequence && collection && policy.nil === "omit" && policy.empty === "as_empty";
    const absentList = repeatedSequence && spec.default?.present !== true;
    readElems.push(
      `    { to: ${q(rule.to)}, names: ${q(names)}, ns: ${accept}, collection: ${collection}, dec: ${dec}${absentList ? ", absentList: true" : ""} },`,
    );
    writeElems.push(
      `    { to: ${q(rule.to)}, name: ${q(first)}, ns: ${out}, collection: ${collection}, enc: ${enc ?? "null"}, child: ${child ?? "null"}, cdata: ${rule.cdata === true}, nil: ${q(policy.nil)}, empty: ${q(policy.empty)}${repeatedSequence ? ", skipEmptyCollection: true" : ""} },`,
    );
  }

  const root = mapping.root === null || mapping.root === undefined ? null : mapping.root.element;
  if (root !== null && (typeof root !== "string" || root === "")) refuse.raise("invalid_document", "root element needs a name");
  // A namespaced model also accepts a root with no namespace, read as if it applied (Ruby does; the mapping's
  // prefix is only the writer's preferred prefix, mml declares "mml"). A different non-empty namespace is refused.
  const rootAccept = acceptList(own.uri !== null ? [own.uri, null] : [own.uri]);
  const readSpec = [
    `const RSPEC_${cls}: x.ModelSpec = {`,
    `  id: ${q(id)}, root: ${q(root)}, ns: ${rootAccept}, ordered: ${ordered}, mixed: ${mixed}, tokens: ${tokens},`,
    "  attrs: [", ...readAttrs, "  ],",
    `  any: ${anyAttribute === null ? "null" : q({ to: anyAttribute, claimed: [...new Set(claimedAttrs)].sort(byCodePoint) })},`,
    "  elems: [", ...readElems, "  ],",
    `  content: ${readContent},`,
    "};",
  ];
  const refusal = writerRefusals.length === 0 ? "null" : q(`unsupported XML writer mapping: ${writerRefusals.join("; ")}`);
  const writeSpec = [
    `const WSPEC_${cls}: x.WSpec = {`,
    `  id: ${q(id)}, ordered: ${tokens}, refusal: ${refusal},`,
    "  attrs: [", ...writeAttrs, "  ],",
    `  any: ${q(anyAttribute)},`,
    "  elems: [", ...writeElems, "  ],",
    `  content: ${writeContent},`,
    "};",
  ];
  const reader = [
    ...readSpec, "",
    `export function read${cls}(el: x.El): m.${cls} {`,
    `  return x.readModel(el, RSPEC_${cls}, m.${cls});`,
    "}", "",
  ].join("\n");
  const writer = [
    ...writeSpec, "",
    `export function write${cls}(w: x.Writer, host: Node | null, v: m.${cls}, name: string, ns: x.NsOut | null) {`,
    `  return x.writeModel(w, WSPEC_${cls}, v, name, ns, host);`,
    "}", "",
  ].join("\n");
  const rootNs = nsOut(own.uri, own.prefix);
  const codec =
    `export const codec${cls} = x.xmlCodec<m.${cls}>(RSPEC_${cls}, read${cls}, ` +
    (root === null ? "null" : `(w, v) => write${cls}(w, null, v, ${q(root)}, ${rootNs})`) +
    ");\n";
  return { reader, writer, codec };
}

/**
 * Emits model-specific namespace-aware XML readers and writers under `xml/`:
 * `runtime.ts` (fixed moxml-ts helpers), `codecs.ts` (one reader, writer and
 * codec per mapped model, all static code) and `index.ts`. Mappings this
 * emitter cannot reproduce faithfully are refused by name
 * (`unsupported_mapping`): at generation for readers, and for writers either
 * at generation or, for features moxml-ts lacks (CDATA output), when the
 * writer is called.
 */
export function createXmlEmitter(options: XmlEmitterOptions = {}): Emitter {
  const contracts = fromSubdirectory(options.contractsModule ?? DEFAULT_CONTRACTS_MODULE);
  return {
    name: "xml",
    emit(bundle: Bundle, bindings: Bindings): SourceMap {
      const ids = Object.keys(bundle.models).sort(byCodePoint);
      const classNames = new Map<ModelId, string>();
      for (const id of ids) {
        const doc = bundle.models[id];
        if (doc !== undefined) classNames.set(id, targetClassName(doc.model, doc.register, id));
      }
      const ctx = new Context(bundle, bindings, classNames);
      const parts: ModelPlan[] = [];
      const registry: string[] = [];
      for (const id of ids) {
        const doc = bundle.models[id];
        const mapping = ctx.mapping(id);
        const cls = classNames.get(id);
        if (doc === undefined || mapping === undefined || cls === undefined) continue;
        parts.push(emitModel(ctx, id, doc, cls, mapping));
        registry.push(`  ${q(id)}: codec${cls},`);
      }
      const body =
        parts.length === 0
          ? [HEADER, "export const CODECS = {} as const;", ""]
          : [
              HEADER,
              'import type { Node } from "moxml-ts";',
              'import * as m from "../models.js";',
              'import * as x from "./runtime.js";',
              ...ctx.importLines(),
              "",
              ...ctx.tables,
              ...(ctx.tables.length > 0 ? [""] : []),
              ...parts.flatMap((p) => [p.reader, p.writer, p.codec]),
              "/** Every codec by model ID. */",
              "export const CODECS = {",
              ...registry,
              "} as const;",
              "",
            ];
      return new Map([
        ["xml/codecs.ts", body.join("\n")],
        ["xml/index.ts", [HEADER, 'export * from "./codecs.js";', 'export { XmlError, xmlCodec } from "./runtime.js";', 'export type { XmlCodec, El } from "./runtime.js";', ""].join("\n")],
        ["xml/runtime.ts", xmlRuntimeSource(contracts)],
      ]);
    },
  };
}

export const xmlEmitter: Emitter = createXmlEmitter();
