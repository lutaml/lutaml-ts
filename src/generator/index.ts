import type {
  Bindings,
  Bundle,
  Emitter,
  GenerateModels,
  ModelId,
  SourceMap,
} from "../contracts.js";
import { compareBytes } from "../lml/validator.js";
import { emitClass } from "./emit.js";
import { NameTable, fail, isIdentifier, targetClassName } from "./names.js";
import { PlanContext } from "./plan.js";
import { runtimeSource } from "./runtime-source.js";

export interface GenerateOptions {
  /** Module the generated runtime imports the sentinel and token types from. */
  readonly contractsModule?: string;
}

const DEFAULT_CONTRACTS_MODULE = "lutaml-model-ts";
const RESERVED_EMITTER_NAMES = new Set(["runtime", "models", "index"]);
const EMITTER_NAME = /^[a-z][a-z0-9]*$/;
const HEADER = "// Generated by lutaml-model-ts. Do not edit.\n";

/**
 * Emits strict static TypeScript classes and validators for every model in
 * the bundle: `runtime.ts`, `models.ts` and `index.ts`. Output depends only on
 * the bundle and bindings. No schema-provided code is evaluated.
 */
export const generateModels: GenerateModels = (bundle, bindings) =>
  generateModelsWith(bundle, bindings, []);

/**
 * As {@link generateModels}, additionally merging model-specific extension
 * emitters. Each emitter writes only under `<name>/` and must provide
 * `<name>/index.ts`; `index.ts` re-exports it as namespace `<name>`.
 */
export function generateModelsWith(
  bundle: Bundle,
  bindings: Bindings,
  emitters: readonly Emitter[],
  options: GenerateOptions = {},
): SourceMap {
  const ids = Object.keys(bundle.models).sort(compareBytes);
  const names = new NameTable();
  const classNames = new Map<ModelId, string>();
  for (const id of ids) {
    const doc = bundle.models[id];
    if (doc === undefined) continue;
    if (id !== `${doc.model}@${doc.register}`) {
      fail({ reason: "invalid_document", model_id: id, location: `/models/${id}`, detail: "key is not model@register" });
    }
    const className = targetClassName(doc.model, doc.register, id);
    classNames.set(id, names.claim(className, id, id));
    names.claim(`${className}Init`, `${id} (init type)`, id);
  }
  for (const root of bundle.roots) {
    if (!classNames.has(root)) {
      fail({ reason: "dangling_reference", model_id: root, location: "/roots", detail: "root is not in the bundle" });
    }
  }
  for (const id of Object.keys(bundle.value_types)) {
    if (id.startsWith("builtin:")) {
      fail({ reason: "invalid_document", model_id: id, location: "/value_types", detail: "builtin: is a reserved binding prefix" });
    }
  }

  const ctx = new PlanContext(bundle, bindings, classNames);
  const classes: string[] = [];
  for (const id of ids) {
    const doc = bundle.models[id];
    const className = classNames.get(id);
    if (doc !== undefined && className !== undefined) classes.push(emitClass(ctx, className, id, doc));
  }

  const imports = ctx.boundImports().map((bound) => {
    const exported = bound.binding.export;
    const parts = [
      `type ${exported} as ${bound.alias}`,
      `is${exported} as ${bound.alias}_is`,
      ...(bound.parse ? [`parse${exported} as ${bound.alias}_parse`] : []),
    ];
    return `import { ${parts.join(", ")} } from ${JSON.stringify(bound.binding.module)};`;
  });
  const registry = ids.map((id) => `  ${JSON.stringify(id)}: ${classNames.get(id) ?? ""},`);
  const models = [
    HEADER,
    'import * as rt from "./runtime.js";',
    ...imports,
    "",
    ...ctx.valueConstLines,
    ...(ctx.valueConstLines.length > 0 ? [""] : []),
    ...classes,
    "/** Every generated model class by model ID. */",
    "export const MODELS = {",
    ...registry,
    "} as const;",
    "",
    `export const ROOT_MODEL_IDS: readonly string[] = ${JSON.stringify([...bundle.roots].sort(compareBytes))};`,
    "",
  ].join("\n");

  const files = new Map<string, string>();
  files.set("runtime.ts", runtimeSource(options.contractsModule ?? DEFAULT_CONTRACTS_MODULE));
  files.set("models.ts", models);
  const extensionExports = mergeEmitters(bundle, bindings, emitters, files);
  files.set(
    "index.ts",
    [
      HEADER,
      'export * from "./models.js";',
      'export { ABSENT, ValidationError } from "./runtime.js";',
      'export type { Absent, Maybe, Violation, ViolationCode } from "./runtime.js";',
      ...extensionExports,
      "",
    ].join("\n"),
  );
  return new Map([...files].sort(([a], [b]) => compareBytes(a, b)));
}

function mergeEmitters(
  bundle: Bundle,
  bindings: Bindings,
  emitters: readonly Emitter[],
  files: Map<string, string>,
): string[] {
  const seen = new Set<string>();
  const exports: string[] = [];
  for (const emitter of [...emitters].sort((a, b) => compareBytes(a.name, b.name))) {
    const { name } = emitter;
    if (!EMITTER_NAME.test(name) || RESERVED_EMITTER_NAMES.has(name) || !isIdentifier(name)) {
      fail({ reason: "invalid_document", detail: `emitter name ${JSON.stringify(name)} is not allowed` });
    }
    if (seen.has(name)) fail({ reason: "duplicate_id", detail: `emitter ${name} registered twice` });
    seen.add(name);
    const produced = emitter.emit(bundle, bindings);
    for (const [path, text] of [...produced].sort(([a], [b]) => compareBytes(a, b))) {
      const segments = path.split("/");
      if (segments[0] !== name || segments.some((s) => s === "" || s === "." || s === "..") || path.includes("\\")) {
        fail({ reason: "invalid_document", detail: `emitter ${name} wrote outside ${name}/: ${path}` });
      }
      if (files.has(path)) fail({ reason: "duplicate_id", detail: `emitter file ${path} collides` });
      files.set(path, text);
    }
    if (!produced.has(`${name}/index.ts`)) {
      fail({ reason: "invalid_document", detail: `emitter ${name} must provide ${name}/index.ts` });
    }
    exports.push(`export * as ${name} from "./${name}/index.js";`);
  }
  return exports;
}
