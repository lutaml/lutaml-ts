const DEFAULT_CONTRACTS_MODULE = "lutaml-model-ts";
const HEADER = "// Generated by lutaml-model-ts. Do not edit.\n";
const NIL_POLICIES = new Set(["omit", "as_nil", "as_empty"]);
const STRING_FAMILY = new Set(["string", "token", "uri", "email", "hostname", "ip", "symbol", "date", "date_time", "time", "time_without_date", "duration",
  "email_address", "ip_v4_address", "ip_v6_address", "uuid", "reference", "uri_reference", "date_with_timezone", "date_time_with_timezone", "day_time_duration", "year_month_duration"]);
const EXACT_BUILTINS = new Set(["decimal", "rational"]);
const KNOWN_RULE_KEYS = new Set(["key", "to", "render", "discriminator"]);

/** Wire shape an empty value is recognised by. */
type Shape = "scalar" | "text" | "hash" | "list";

interface Wire {
  /** Expression of `(v: unknown) => T` for one element. */
  readonly dec: string;
  /** Expression of `(x: T) => unknown` for one element. */
  readonly enc: string;
  readonly shape: Shape;
}

/** Rewrites a module specifier for use from one directory below the root. */
export function fromSubdirectory(specifier: string): string {
  if (specifier.startsWith("./")) return "." + specifier;
  if (specifier.startsWith("../")) return "../" + specifier;
  return specifier;
}

class Refusal {
  constructor(
    private readonly format: KeyValueFormat,
    private readonly modelId: ModelId,
  ) {}

  unsupported(detail: string, attribute?: string): never {
    return this.raise("unsupported_mapping", detail, attribute);
  }

  raise(reason: ErrorDetail["reason"], detail: string, attribute?: string): never {
    throw new LmlError({
      reason,
      model_id: this.modelId,
      format: this.format,
      detail,
      ...(attribute === undefined ? {} : { attribute }),
    });
  }
}

interface BoundUse {
  readonly alias: string;
  readonly binding: TypeBinding;
}

class Context {
  private readonly bound = new Map<string, BoundUse>();
  readonly tables: string[] = [];

  constructor(
    readonly format: KeyValueFormat,
    readonly bundle: Bundle,
    readonly bindings: Bindings,
    readonly classNames: ReadonlyMap<ModelId, string>,
  ) {}

  mapping(id: ModelId): KeyValueMapping | undefined {
    const doc = Object.hasOwn(this.bundle.models, id) ? this.bundle.models[id] : undefined;
    // A model without `mappings` has no mappings.
    return (doc?.mappings as Partial<Record<string, KeyValueMapping>> | undefined)?.[this.format];
  }

  bind(binding: TypeBinding): BoundUse {
    const id = binding.module + "\u0000" + binding.export;
    const known = this.bound.get(id);
    if (known !== undefined) return known;
    const made = { alias: `_b${this.bound.size}`, binding };
    this.bound.set(id, made);
    return made;
  }

  importLines(): string[] {
    return [...this.bound.values()].map(({ alias, binding }) => {
      const e = binding.export;
      return `import { format${e} as ${alias}_format, parse${e} as ${alias}_parse } from ${JSON.stringify(fromSubdirectory(binding.module))};`;
    });
  }
}

function builtinWire(ctx: Context, name: string, refuse: Refusal, attribute: string, bindingKey: string): Wire {
  if (name === "double") refuse.raise("unsupported_type", name, attribute);
  if (STRING_FAMILY.has(name)) return { dec: "w.dStr", enc: "w.eStr", shape: "text" };
  if (EXACT_BUILTINS.has(name)) {
    const binding = ctx.bindings.types[`builtin:${name}`];
    if (binding === undefined) {
      return refuse.raise("missing_type_binding", `exact ${name} needs a binding under builtin:${name}`, attribute);
    }
    return boundWire(ctx, binding, bindingKey);
  }
  switch (name) {
    case "boolean": return { dec: "w.dBool", enc: "w.eBool", shape: "scalar" };
    case "positive_integer":
    case "non_negative_integer":
    case "integer": return { dec: "w.dInt", enc: "w.eInt", shape: "scalar" };
    case "float": return { dec: "w.dFloat", enc: "w.eFloat", shape: "scalar" };
    case "qname": return { dec: "w.dQName", enc: "w.eQName", shape: "scalar" };
    case "base64_binary": return { dec: "w.dBase64", enc: "w.eBase64", shape: "scalar" };
    case "hex_binary": return { dec: "w.dHex", enc: "w.eHex", shape: "scalar" };
    case "hash": return { dec: "w.dHash", enc: "w.eHash", shape: "hash" };
    default: return refuse.raise("unknown_type", name, attribute);
  }
}

function boundWire(ctx: Context, binding: TypeBinding, _key: string): Wire {
  const use = ctx.bind(binding);
  return {
    dec: `(v) => w.dBound(v, ${use.alias}_parse)`,
    enc: `(x) => w.eBound(x, ${use.alias}_format)`,
    shape: "scalar",
  };
}

function polymorphicWire(ctx: Context, attr: AttributeSpec, disc: Discriminator | undefined, refuse: Refusal): Wire {
  if (disc === undefined || attr.type.kind !== "model") return refuse.raise("invalid_document", "not polymorphic", attr.name);
  const base = ctx.mapping(attr.type.id);
  const baseRule = base?.rules.find((rule) => rule.to === disc.attribute);
  if (baseRule === undefined) {
    return refuse.unsupported(`discriminator attribute ${disc.attribute} has no ${ctx.format} rule on ${attr.type.id}`, attr.name);
  }
  const wireCases = Object.keys(disc.cases).sort(compareBytes);
  const targets = [...new Set(Object.values(disc.cases))].sort(compareBytes);
  if (targets.length === 0) return refuse.raise("unknown_discriminator", "no cases", attr.name);
  const classOf = (target: ModelId): string => {
    const name = ctx.classNames.get(target);
    if (name === undefined || ctx.mapping(target) === undefined) {
      return refuse.unsupported(`discriminator case ${target} has no ${ctx.format} mapping`, attr.name);
    }
    return name;
  };
  const baseClass = classOf(attr.type.id);
  const ladderTargets = targets.includes(attr.type.id) ? targets : [...targets, attr.type.id];
  const union = ladderTargets.map((t) => `m.${classOf(t)}`).join(" | ");
  const table = `POLY${ctx.tables.length}`;
  const entries = wireCases.map((c) => `[${JSON.stringify(c)}, decode${classOf(disc.cases[c] as ModelId)}]`);
  ctx.tables.push(
    `const ${table}: ReadonlyMap<string, (v: unknown) => ${union}> = new Map<string, (v: unknown) => ${union}>([${entries.join(", ")}]);`,
  );
  const tests = ladderTargets.map((t) => `x instanceof m.${classOf(t)} ? encode${classOf(t)}(x) : `).join("");
  return {
    dec: `(v) => w.poly(v, ${JSON.stringify(baseRule.key)}, ${table}, decode${baseClass})`,
    enc: `(x: ${union}) => ${tests}w.unknownCase()`,
    shape: "scalar",
  };
}

function elementWire(ctx: Context, attr: AttributeSpec, disc: Discriminator | undefined, refuse: Refusal): Wire {
  const { type } = attr;
  if (type.kind === "builtin") return builtinWire(ctx, type.name, refuse, attr.name, type.name);
  if (type.kind === "value") {
    const spec = Object.hasOwn(ctx.bundle.value_types, type.id) ? ctx.bundle.value_types[type.id] : undefined;
    if (spec === undefined) return refuse.raise("dangling_reference", `value type ${type.id}`, attr.name);
    const binding = Object.hasOwn(ctx.bindings.types, type.id) ? ctx.bindings.types[type.id] : undefined;
    if (binding !== undefined) {
      if (spec.base === "double") refuse.raise("unsupported_type", spec.base, attr.name);
      return boundWire(ctx, binding, type.id);
    }
    return builtinWire(ctx, spec.base, refuse, attr.name, type.id);
  }
  if (disc !== undefined) return polymorphicWire(ctx, attr, disc, refuse);
  const cls = ctx.classNames.get(type.id);
  if (cls === undefined) return refuse.raise("dangling_reference", `model ${type.id}`, attr.name);
  if (ctx.mapping(type.id) === undefined) {
    return refuse.unsupported(`referenced model ${type.id} has no ${ctx.format} mapping`, attr.name);
  }
  return { dec: `decode${cls}`, enc: `encode${cls}`, shape: "hash" };
}

function attributeWire(ctx: Context, doc: ModelDocument, id: ModelId, attr: AttributeSpec, refuse: Refusal): Wire {
  // One source of truth with the model generator: attribute-level and every
  // format's rule-level discriminator must agree, or generation refuses.
  const element = elementWire(ctx, attr, effectiveDiscriminator(doc, attr, id), refuse);
  const collection = (attr as Partial<AttributeSpec>).collection ?? false;
  if (collection === false) return element;
  return { dec: `w.dList(${element.dec})`, enc: `w.eList(${element.enc})`, shape: "list" };
}

interface Policies {
  readonly nil: string;
  readonly empty: string;
}

function policies(rule: KeyValueRule, refuse: Refusal): Policies {
  const render = rule.render ?? {};
  for (const name of Object.keys(render)) {
    if (name !== "nil" && name !== "empty" && name !== "default") {
      refuse.unsupported(`render ${name} is not a key-value render policy`, rule.to);
    }
  }
  if (render["default"] !== undefined && typeof render["default"] !== "boolean") {
    refuse.unsupported("render default must be boolean", rule.to);
  }
  const pick = (name: "nil" | "empty"): string => {
    const value = render[name] ?? "omit";
    if (typeof value !== "string" || !NIL_POLICIES.has(value)) {
      return refuse.unsupported(`render ${name} policy ${JSON.stringify(value)}`, rule.to);
    }
    return value;
  };
  return { nil: pick("nil"), empty: pick("empty") };
}

function validateMapping(mapping: KeyValueMapping, doc: ModelDocument, refuse: Refusal): void {
  const extra = mapping as KeyValueMapping & { readonly [name: string]: unknown };
  for (const name of Object.keys(extra)) {
    if (name === "rules") continue;
    if (name === "namespace") {
      const ns = extra[name] as { readonly mode?: string } | undefined;
      if (ns !== undefined && ns.mode !== "inherit") refuse.unsupported("namespace on a key-value mapping");
      continue;
    }
    refuse.unsupported(`mapping-level ${name} is not supported`);
  }
  const attributes = new Set(doc.attributes.map((a) => a.name));
  const seenAttr = new Set<string>();
  const seenKey = new Set<string>();
  for (const rule of mapping.rules) {
    for (const name of Object.keys(rule)) {
      if (!KNOWN_RULE_KEYS.has(name)) refuse.unsupported(`rule-level ${name} is not supported`, rule.to);
    }
    if (!attributes.has(rule.to)) refuse.raise("dangling_reference", `rule maps unknown attribute ${rule.to}`, rule.to);
    if (seenAttr.has(rule.to)) refuse.unsupported("several rules on one attribute", rule.to);
    seenAttr.add(rule.to);
    if (!Array.isArray(rule.key) || rule.key.length === 0) refuse.raise("invalid_document", "rule needs wire keys", rule.to);
    for (const key of rule.key) {
      if (seenKey.has(key)) refuse.unsupported(`duplicate wire key ${JSON.stringify(key)}`, rule.to);
      seenKey.add(key);
    }
  }
}

function emitModel(ctx: Context, id: ModelId, doc: ModelDocument, cls: string, mapping: KeyValueMapping): string {
  const refuse = new Refusal(ctx.format, id);
  validateMapping(mapping, doc, refuse);
  const decode: string[] = [];
  const encode: string[] = [];
  const wireKeys: Record<string, string> = {};
  for (const rule of mapping.rules) {
    const attr = doc.attributes.find((a) => a.name === rule.to) as AttributeSpec;
    const wire = attributeWire(ctx, doc, id, attr, refuse);
    const policy = policies(rule, refuse);
    const first = rule.key[0] as string;
    wireKeys[rule.to] = first;
    decode.push(`  w.field(o, ${JSON.stringify(rule.key)}, init, ${JSON.stringify(rule.to)}, ${wire.dec});`);
    encode.push(
      `  w.render(out, ${JSON.stringify(first)}, x${access(rule.to)}, ${wire.enc}, ${JSON.stringify(policy.nil)}, ${JSON.stringify(policy.empty)}, ${JSON.stringify(wire.shape)});`,
    );
  }
  // Ruby key-value ingestion checks empty/missing required collections even
  // inside a choice. Nonempty choice collections use the source fast path;
  // their batch counts remain deferred to explicit group validation.
  const choiceNames = compileChoices(doc, id).names;
  const eagerChoices = doc.attributes.filter((attribute) => choiceNames.has(attribute.name) && attribute.collection !== false && attribute.collection.min > 0);
  const eager = eagerChoices.map((attribute) => {
    const key = wireKeys[attribute.name];
    if (key === undefined) return "";
    const value = `model${access(attribute.name)}`;
    return `  if (!Array.isArray(${value}) || ${value}.length === 0) throw new w.WireError("invalid_document", "required choice collection is empty", ${JSON.stringify("/" + key.replaceAll("~", "~0").replaceAll("/", "~1"))}, m.${cls}.modelId);`;
  }).filter(Boolean);
  return [
    `export function decode${cls}(v: unknown): m.${cls} {`,
    "  const o = w.object(v);",
    "  const init: Record<string, unknown> = {};",
    ...decode,
    ...(eager.length === 0 ? [`  return w.build(m.${cls}, init, ${JSON.stringify(wireKeys)}, m.${cls}.modelId);`] : [
      `  const model = w.build(m.${cls}, init, ${JSON.stringify(wireKeys)}, m.${cls}.modelId);`, ...eager, "  return model;",
    ]),
    "}",
    "",
    `export function encode${cls}(x: m.${cls}): w.Rec {`,
    "  const out: Record<string, unknown> = {};",
    ...encode,
    "  return out;",
    "}",
    "",
    `export const codec${cls} = w.${ctx.format}Codec<m.${cls}>(m.${cls}.modelId, decode${cls}, encode${cls});`,
    "",
  ].join("\n");
}

/**
 * Emits model-specific key-value codecs under `<format>/`: `runtime.ts`
 * (fixed wire helpers), `codecs.ts` (one decode/encode pair and codec per
 * mapped model, all static code) and `index.ts`. Mappings this emitter
 * cannot reproduce faithfully are refused by name (`unsupported_mapping`).
 */
export function createKeyValueEmitter(format: KeyValueFormat, options: CodecOptions = {}): Emitter {
  const contracts = fromSubdirectory(options.contractsModule ?? DEFAULT_CONTRACTS_MODULE);
  return {
    name: format,
    emit(bundle: Bundle, bindings: Bindings): SourceMap {
      const ids = Object.keys(bundle.models).sort(compareBytes);
      const classNames = new Map<ModelId, string>();
      for (const id of ids) {
        const doc = bundle.models[id];
        if (doc !== undefined) classNames.set(id, targetClassName(doc.model, doc.register, id));
      }
      const ctx = new Context(format, bundle, bindings, classNames);
      const bodies: string[] = [];
      const registry: string[] = [];
      for (const id of ids) {
        const doc = bundle.models[id];
        const mapping = ctx.mapping(id);
        const cls = classNames.get(id);
        if (doc === undefined || mapping === undefined || cls === undefined) continue;
        bodies.push(emitModel(ctx, id, doc, cls, mapping));
        registry.push(`  ${JSON.stringify(id)}: codec${cls},`);
      }
      const codecs =
        bodies.length === 0
          ? [HEADER, "export const CODECS = {} as const;", ""]
          : [
              HEADER,
              'import * as m from "../models.js";',
              'import * as w from "./runtime.js";',
              ...ctx.importLines(),
              "",
              ...ctx.tables,
              ...(ctx.tables.length > 0 ? [""] : []),
              ...bodies,
              "/** Every codec by model ID. */",
              "export const CODECS = {",
              ...registry,
              "} as const;",
              "",
            ];
      const runtimeExports =
        format === "json"
          ? `export { WireError, jsonCodec } from "./runtime.js";\nexport type { JsonCodec, Rec } from "./runtime.js";`
          : `export { WireError, yamlCodec } from "./runtime.js";\nexport type { YamlCodec, YamlLibrary, Rec } from "./runtime.js";`;
      return new Map([
        [`${format}/codecs.ts`, codecs.join("\n")],
        [`${format}/index.ts`, [HEADER, 'export * from "./codecs.js";', runtimeExports, ""].join("\n")],
        [`${format}/runtime.ts`, codecRuntimeSource(contracts, format)],
      ]);
    },
  };
}

export const jsonEmitter: Emitter = createKeyValueEmitter("json");
export const yamlEmitter: Emitter = createKeyValueEmitter("yaml");

/** generateJsonCodecs(bundle, bindings): the 06e contract entry point. */
export const generateJsonCodecs: GenerateJsonCodecs = (bundle, bindings) => jsonEmitter.emit(bundle, bindings);
